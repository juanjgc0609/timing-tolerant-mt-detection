"""Task 2M validation: the generalised code reproduces C16 (seed 999, day 100723, networks 2400-2413) bit for bit.
    python t2m_validate.py noise                      V0 noise array and slot bookkeeping of t2m_data.py = C16's
    python t2m_validate.py geometry                   V1 subsets, frames and slots of every C16 network and cell
    python t2m_validate.py parts NEWDIR [C16DIR]      V2 part files regenerated by t2m_run.py = C16 parts (all fields
                                                      except wall-clock timings and the three fields t2m adds)
No window of a new seed or a new day is generated here.
"""
import glob
import json
import os
import sys

import numpy as np

WORK = os.path.dirname(os.path.abspath(__file__))
C16_NOISE = os.path.join(WORK, "explore_contrib", "out", "c16_noise")
C16_PARTS = os.path.join(WORK, "explore_contrib", "out", "c16_eval_parts")
NEW_NOISE = os.path.join(WORK, "t2m_out", "noise", "100723")
REPRO_CFG = os.path.join(WORK, "t2m_out", "cfg_c16repro.json")
TIMING = {"t_cat", "t_setup", "t_total"}
ADDED = {"seed", "day", "stations"}


def v0():
    a = np.load(os.path.join(C16_NOISE, "c16_noise.npy"), mmap_mode="r")
    b = np.load(os.path.join(NEW_NOISE, "noise.npy"), mmap_mode="r")
    same = a.shape == b.shape and a.dtype == b.dtype and bool(np.array_equal(a, b))
    ma = json.load(open(os.path.join(C16_NOISE, "c16_meta.json")))
    mb = json.load(open(os.path.join(NEW_NOISE, "meta.json")))
    keys = [k for k in ma if k != "channels"]
    diff = [k for k in keys if ma[k] != mb.get(k)]
    ch = all({kk: vv for kk, vv in mb["channels"][c].items() if kk != "n_extra_dropped"} == ma["channels"][c]
             for c in ma["channels"]) and set(ma["channels"]) == set(mb["channels"])
    print(f"V0 noise array {b.shape} {b.dtype} identical to c16_noise.npy: {same}; meta keys identical "
          f"({len(keys)} keys + channels): {not diff and ch} {diff}")
    return same and not diff and ch


def v1():
    import t2m_lib as L2
    L2.configure_file(REPRO_CFG)
    ok, n = True, 0
    for fn in sorted(glob.glob(os.path.join(C16_PARTS, "*.json"))):
        p = json.load(open(fn))
        sub, STA = L2.subset(p["cell"], p["net"])
        sl = L2.slots(p["net"])
        ok &= sub.tolist() == p["sub"] and STA.tolist() == p["STA"] and sl == p["slots"]
        if p["arm"] == "REAL":
            pool = L2.cat_pool(sl)
            ok &= set(p["cat_slots"]) <= set(pool[:p["cat_drawn"]])
        n += 1
    print(f"V1 subsets, station coordinates, slot lists and catalogue pools of {n} C16 parts (2 arms x 3 cells x "
          f"12 networks) reproduced: {ok}")
    return ok


def strip(p):
    q = {k: v for k, v in p.items() if k not in TIMING and k not in ADDED}
    q["rows"] = [{k: v for k, v in r.items() if k != "sec"} for r in p["rows"]]
    return q


def v2(newdir, c16dir=C16_PARTS):
    ok, n = True, 0
    for fn in sorted(glob.glob(os.path.join(newdir, "*.json"))):
        a = json.load(open(fn))
        b = json.load(open(os.path.join(c16dir, os.path.basename(fn))))
        sa, sb = strip(a), strip(b)
        same = json.dumps(sa, sort_keys=True) == json.dumps(sb, sort_keys=True)
        nat = sum(len(v) for r in a["rows"] for v in r["atoms"].values())
        print(f"   {os.path.basename(fn)}: identical {same} ({len(a['rows'])} windows, {nat} atoms, catalogue drawn "
              f"{a['cat_drawn']}, wall {a['t_total']:.0f} s vs C16 {b['t_total']:.0f} s)")
        if not same:
            for k in sorted(set(sa) | set(sb)):
                if json.dumps(sa.get(k), sort_keys=True) != json.dumps(sb.get(k), sort_keys=True):
                    print("      differs:", k)
        ok &= same
        n += 1
    print(f"V2 {n} regenerated parts identical to C16 (all fields except timings): {ok and n > 0}")
    return ok and n > 0


def plan(cfgp):
    """seed-independent checks of a 2M configuration (no random stream of the seed is touched, no window generated):
    blocks, slot counts per use against the window counts, catalogue pool size, disjointness and eligibility of all
    slots, stations per day, and the possible unilateral subsets of each day as theta sweeps [0, 2 pi)."""
    import t2m_lib as L2
    c = L2.configure_file(cfgp)
    nw = L2.CFG["nwin"]
    ok = True
    used = {}
    pools, per = [], {k: [] for k in ("cat", "STD", "DENSE", "NOISE")}
    for j in L2.CFG["nets"]:
        di, blk = L2.block(j)
        sl = L2.slots(j)
        el = set(L2._DAYS[di][1]["eligible"])
        u = sl["cat"] + sl["STD"] + sl["DENSE"] + sl["NOISE"]
        ok &= len(set(u)) == len(u) and set(u) <= el and all(len(sl[k]) >= nw[k] for k in ("STD", "DENSE", "NOISE"))
        for s in u:
            ok &= (di, s) not in used
            used[(di, s)] = j
        pools.append(len(L2.cat_pool(sl)))
        for k in per:
            per[k].append(len(sl[k]))
    print(f"PLAN {os.path.basename(cfgp)}: seed {c['seed']}, {len(L2.CFG['nets'])} networks per cell "
          f"(j {L2.CFG['nets'][0]}-{L2.CFG['nets'][-1]}), blocks per day {L2.CFG['nblocks']}, windows {nw}, methods "
          f"{L2.CFG['methods']}")
    for di, (_a, m) in enumerate(L2._DAYS):
        x, y = np.array(m["x_km"]), np.array(m["y_km"])
        az = np.arctan2(y, x)
        subs = {}
        for th in np.linspace(0, 2 * np.pi, 3600, endpoint=False):
            dd = np.abs(np.angle(np.exp(1j * (az - th))))
            s = tuple(np.sort(np.argsort(dd, kind="stable")[:8]).tolist())
            if s not in subs:
                a = np.sort(np.degrees(az[list(s)]) % 360)
                subs[s] = float(np.max(np.diff(np.r_[a, a[0] + 360])))
        r = np.hypot(x, y)
        print(f"   day {m.get('day')}: {len(m['stations'])} stations {','.join(m['stations'])}; eligible slots "
              f"{len(m['eligible'])} ({len(m['eligible']) * 40 / 3600:.1f} h); distances to frame origin {r.min():.1f}-"
              f"{r.max():.1f} km; possible unilateral 8-subsets {len(subs)}, max azimuthal gap "
              f"{min(subs.values()):.0f}-{max(subs.values()):.0f} deg; level quantiles 5/50/95/99 "
              + "/".join(f"{m['rel_level_q'][q][0] if isinstance(m['rel_level_q'][q], list) else m['rel_level_q'][q]:.2f}"
                         for q in ("5", "50", "95", "99")))
    print(f"   slots per use and network: cat {min(per['cat'])}-{max(per['cat'])}, STD {min(per['STD'])}-"
          f"{max(per['STD'])}, DENSE {min(per['DENSE'])}-{max(per['DENSE'])}, NOISE {min(per['NOISE'])}-"
          f"{max(per['NOISE'])}; catalogue pool {min(pools)}-{max(pools)} (C16 REAL drew at most 38)")
    print(f"   slots disjoint, eligible and sufficient: {ok}")
    return ok


if __name__ == "__main__":
    what = sys.argv[1]
    if what == "noise":
        r = v0()
    elif what == "geometry":
        r = v1()
    elif what == "plan":
        r = all([plan(c) for c in sys.argv[2:]])
    else:
        r = v2(*sys.argv[2:])
    print("PASS" if r else "FAIL")
